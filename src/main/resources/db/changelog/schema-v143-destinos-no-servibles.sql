    postal_to     VARCHAR(16) NOT NULL,
    note          VARCHAR(120),
    created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    created_by    VARCHAR(64),
    updated_by    VARCHAR(64)
);

CREATE INDEX IF NOT EXISTS ix_unserviceable_country ON carrier_unserviceable_zone (country_code);

COMMENT ON TABLE carrier_unserviceable_zone IS
    'Rangos de código postal a los que el transportista NO entrega, dentro de países que sí cubre.';

