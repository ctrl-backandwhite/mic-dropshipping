--
-- Se venden pedidos a sitios donde el transportista no entrega.
--
-- La cobertura se comprueba POR PAÍS (`cainiao_shipping_zone`), pero YunExpress excluye zonas concretas
-- dentro de países que sí sirve. Su lista `不可到地区清单` deja fuera, en España, cinco rangos enteros:
-- Baleares (07), Las Palmas (35), Tenerife (38), Ceuta (51) y Melilla (52). Hoy un cliente de Palma o
-- de Tenerife completa el pedido, paga, y el envío no se puede despachar.
--
-- Portugal tiene el mismo caso con Azores y Madeira (9500-9999), y Francia es el país con más zonas
-- excluidas de todo el documento: sus 535 exclusiones vienen por NOMBRE de ciudad (Polinesia,
-- Guadalupe, Martinica, Guayana, Reunión, Mayotte), y se cubren por rango de código postal —97xxx los
-- departamentos de ultramar y 98xxx las colectividades—, que es más robusto y no depende de acertar
-- con la grafía de cada localidad.
--
-- Alcance: los 12 países de la UE cuyas exclusiones vienen con código postal numérico. Los CP
-- alfanuméricos (Reino Unido) y las listas de «solo estos CP son alcanzables» (Chile, Colombia,
-- Turquía, Chipre) necesitan otro tratamiento y no entran aquí.

